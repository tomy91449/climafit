-- ms-clases, base clases_db. Tablas de la Persona 3 (la tabla evaluacion_climatica la agrega la Persona 4 en V2).

CREATE TABLE clase (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- referencias lógicas a ms-actividades: sin clave foránea (viven en otra base)
    tipo_actividad_id BIGINT       NOT NULL,
    espacio_id        BIGINT       NOT NULL,
    -- copiado del espacio al crear la clase
    al_aire_libre     BOOLEAN      NOT NULL,
    profesor_id       VARCHAR(64)  NOT NULL,
    inicio            TIMESTAMP    NOT NULL,
    duracion_min      INTEGER      NOT NULL,
    cupo              INTEGER      NOT NULL,
    estado            VARCHAR(30)  NOT NULL,
    estado_previo     VARCHAR(30),
    -- bloqueo optimista (@Version)
    version           BIGINT       NOT NULL DEFAULT 0
);

CREATE INDEX idx_clase_profesor_inicio ON clase (profesor_id, inicio);
CREATE INDEX idx_clase_estado_inicio ON clase (estado, inicio);

CREATE TABLE rutina_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id     BIGINT       NOT NULL REFERENCES clase (id),
    -- referencia lógica a ms-actividades
    ejercicio_id BIGINT       NOT NULL,
    orden        INTEGER      NOT NULL,
    indicaciones VARCHAR(500)
);

CREATE INDEX idx_rutina_item_clase ON rutina_item (clase_id);

CREATE TABLE inscripcion (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id   BIGINT      NOT NULL REFERENCES clase (id),
    -- sub del usuario en Keycloak
    alumno_id  VARCHAR(64) NOT NULL,
    estado     VARCHAR(20) NOT NULL,
    fecha_alta TIMESTAMP   NOT NULL,
    CONSTRAINT uq_inscripcion_clase_alumno UNIQUE (clase_id, alumno_id)
);

CREATE INDEX idx_inscripcion_alumno ON inscripcion (alumno_id);

CREATE TABLE cambio_estado (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id        BIGINT       NOT NULL REFERENCES clase (id),
    fecha           TIMESTAMP    NOT NULL,
    -- NULL solo en el primer registro (la clase recién creada)
    estado_anterior VARCHAR(30),
    estado_nuevo    VARCHAR(30)  NOT NULL,
    motivo          VARCHAR(500),
    -- sub del usuario o SISTEMA
    responsable     VARCHAR(64)  NOT NULL,
    inicio_anterior TIMESTAMP,
    inicio_nuevo    TIMESTAMP,
    notificado      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_cambio_estado_clase ON cambio_estado (clase_id, fecha);
CREATE INDEX idx_cambio_estado_pendientes ON cambio_estado (notificado);
